// Task 2: Print even numbers using for loop
// Problem: Write a program that prints even numbers from 2 to 20 using a for loop.
// Hint: Increase loop variable by 2 each time.

#include <iostream>
using namespace std;

int main(){
    for (int i = 2; i <=20; i= i+2){
         cout << i<<endl; 
    }
    return 0;
}